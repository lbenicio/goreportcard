var (
	skipDirs       = []string{"Godeps", "vendor", "third_party", "testdata"}
	skipSuffixes   = []string{".pb.go", ".pb.gw.go", ".generated.go", "bindata.go", "_string.go"}
	skipFirstLines = []string{"code generated", "generated", "autogenerated", "@generated", "code autogenerated", "auto-generated"}
)

// GoFiles returns a slice of Go filenames
// in a given directory.
func GoFiles(dir string) (filenames, skipped []string, err error) {
	visit := func(fp string, fi os.FileInfo, err error) error {
		for _, skip := range skipDirs {
			if strings.Contains(fp, fmt.Sprintf("/%s/", skip)) {
				return nil
			}
		}
		if err != nil {
			fmt.Println(err) // can't walk here,
			return nil       // but continue walking elsewhere
		}
		if fi.IsDir() {
			return nil // not a file.  ignore.
		}
		if !fi.Mode().IsRegular() {
			return nil
		}
		fiName := fi.Name()
		for _, skip := range skipSuffixes {
			if strings.HasSuffix(fiName, skip) {
				skipped = append(skipped, fp)
				return nil
			}
		}
		ext := filepath.Ext(fiName)
		if ext != ".go" {
			return nil
		}

		if autoGenerated(fp) {
			skipped = append(skipped, fp)
			return nil
		}

		filenames = append(filenames, fp)

		return nil
	}

	err = filepath.Walk(dir, visit)

	return filenames, skipped, err
}

// RenameFiles renames the provided filenames to have a ".grc.bk" extension,
// so they will not be considered in future checks.
func RenameFiles(names []string) (err error) {
	for i := range names {
		tmpErr := os.Rename(names[i], names[i]+".grc.bk")
		if tmpErr != nil {
			// save this error, but still continue with other files
			err = tmpErr
		}
	}

	return err
}

// RevertFiles removes the ".grc.bk" extension from files
func RevertFiles(names []string) (err error) {
	for i := range names {
		tmpErr := os.Rename(names[i]+".grc.bk", names[i])
		if tmpErr != nil {
			// save this error, but still continue with other files
			err = tmpErr
		}
	}

	return err
}

// lineCount returns the number of lines in a given file
func lineCount(filepath string) (int, error) {
	out, err := exec.Command("wc", "-l", filepath).Output()
	if err != nil {
		return 0, err
	}

	// wc output is like: 999 filename.go
	count, err := strconv.Atoi(strings.Split(strings.TrimSpace(string(out)), " ")[0])
	if err != nil {
		return 0, fmt.Errorf("could not count lines: %v", err)
	}

	return count, nil
}

// determine whether the Go file was auto-generated
func autoGenerated(fp string) bool {
	file, err := os.Open(fp)
	if err != nil {
		fmt.Println(err)
		return false
	}
	defer file.Close()

	// read first line of file and determine if it might
	// be auto-generated
	scanner := bufio.NewScanner(file)
	scanner.Scan()
	line := strings.ToLower(scanner.Text())
	commentStyles := []string{"// ", "//", "/* ", "/*"}
	for _, skip := range skipFirstLines {
		for i := range commentStyles {
			if strings.HasPrefix(line, commentStyles[i]) && strings.HasPrefix(line[len(commentStyles[i]):], skip) {
				return true
			}
		}
	}
	return false
}

// Error contains the line number and the reason for
// an error output from a command
type Error struct {
	LineNumber  int    `json:"line_number"`
	ErrorString string `json:"error_string"`
}

// FileSummary contains the filename, location of the file
// on GitHub, and all of the errors related to the file
type FileSummary struct {
	Filename string  `json:"filename"`
	FileURL  string  `json:"file_url"`
	Errors   []Error `json:"errors"`
}

var diagnosticPattern = regexp.MustCompile(`^(.+?):([0-9]+)(?::([0-9]+))?:(.*)$`)

func parseDiagnostic(out string) (filename string, lineNumber int, message string, ok bool) {
	matches := diagnosticPattern.FindStringSubmatch(out)
	if matches == nil {
		return "", 0, "", false
	}

	lineNumber, err := strconv.Atoi(matches[2])
	if err != nil {
		return "", 0, "", false
	}

	return matches[1], lineNumber, matches[4], true
}

// AddError adds an Error to FileSummary
func (fs *FileSummary) AddError(out string) error {
	_, lineNumber, message, ok := parseDiagnostic(out)
	if !ok {
		return fmt.Errorf("AddError: could not parse %q", out)
	}

	fs.Errors = append(fs.Errors, Error{LineNumber: lineNumber, ErrorString: message})
	return nil
}

func displayFilename(filename string) string {
	sp := strings.Split(filename, "@")
	if len(sp) < 2 {
		return filename
	}

	fsp := strings.Split(sp[1], "/")

	return filepath.Join(fsp[1:]...)
}

// borrowed from github.com/client9/gosupplychain
// MIT LICENSE: https://github.com/client9/gosupplychain/blob/master/LICENSE
func goPkgInToGitHub(name string) string {
	dir := ""
	var pkgversion string
	var user string
	parts := strings.Split(name, "/")
	if len(parts) < 2 {
		return ""
	}
	if parts[0] != "gopkg.in" {
		return ""
	}

	idx := strings.Index(parts[1], ".")
	if idx != -1 {
		pkgversion = parts[1]
		if len(parts) > 2 {
			dir = "/" + strings.Join(parts[2:], "/")
		}
	} else {
		user = parts[1]
		pkgversion = parts[2]
		if len(parts) > 3 {
			dir = "/" + strings.Join(parts[3:], "/")
		}
	}
	idx = strings.Index(pkgversion, ".")
	if idx == -1 {
		return ""
	}
	pkg := pkgversion[:idx]
	if user == "" {
		user = "go-" + pkg
	}
	version := pkgversion[idx+1:]
	if version == "v0" {
		version = "master"
	}

	return "https://github.com/" + user + "/" + pkg + "/blob/" + version + dir
}

func fileURL(filename string) string {
	f := displayFilename(filename)

	fsp := strings.Split(filename, "@")

	repo := strings.TrimPrefix(fsp[0], "/")

	var ver string
	if len(fsp) > 1 {
		verSp := strings.Split(fsp[1], "/")
		ver = verSp[0]
	}

	var fileURL string
	base := strings.TrimPrefix(repo, "_repos/src/")
	githubBase := base
	if !strings.HasPrefix(githubBase, "github.com/") {
		if i := strings.Index(githubBase, "/github.com/"); i >= 0 {
			githubBase = githubBase[i+1:]
		}
	}
	switch {
	case strings.HasPrefix(base, "golang.org/x/"):
		var pkg string
		if len(strings.Split(base, "/")) >= 3 {
			pkg = strings.Split(base, "/")[2]
		}

		return fmt.Sprintf("https://github.com/golang/%s/blob/master%s", pkg, strings.TrimPrefix(filename, "/"+base))
	case strings.HasPrefix(githubBase, "github.com/"):
		githubParts := strings.Split(githubBase, "/")
		if len(githubParts) >= 3 {
			base = strings.Join(githubParts[:3], "/")
		}

		if ver != "" {
			if strings.Contains(ver, "-") {
				verSp := strings.Split(ver, "-")
				if len(verSp) > 2 {
					ver = strings.Split(ver, "-")[2]
				}
			}

			if strings.Contains(ver, "+incompatible") {
				ver = strings.TrimSuffix(ver, "+incompatible")
			}

			return fmt.Sprintf("https://%s/blob/%s/%s", base, ver, f)
		}

		return fmt.Sprintf("https://%s/blob/master%s", base, strings.TrimPrefix(filename, "/"+base))
	case strings.HasPrefix(base, "gopkg.in/"):
		return goPkgInToGitHub(base) + strings.TrimPrefix(filename, "/"+base)
	}

	return fileURL
}

func makeFilename(fn string) string {
	sp := strings.Split(fn, "/")
	switch {
	case strings.HasPrefix(fn, "/github.com"):
		if len(sp) > 3 {
			return strings.Join(sp[3:], "/")
		}
	case strings.HasPrefix(fn, "/golang.org/x"):
		if len(sp) > 3 {
			return strings.Join(sp[3:], "/")
		}
	case strings.HasPrefix(fn, "/gopkg.in"):
		if len(sp) > 3 {
			return strings.Join(sp[3:], "/")
		}
	}

	return fn
}

func getFileSummaryMap(out *bufio.Scanner, dir, tool string) (map[string]FileSummary, error) {
	fsMap := make(map[string]FileSummary)
outer:
	for out.Scan() {
		line := out.Text()
		if strings.TrimSpace(line) == "" || strings.HasPrefix(line, "# ") {
			continue
		}
		// Go includes module download progress in the analyzer output stream.
		if strings.HasPrefix(line, "go: downloading ") {
			continue
		}

		switch tool {
		case "gofmt":
			line = fmt.Sprintf("%s:1:0: file is not gofmted with -s (gofmt)", strings.TrimSpace(line))
		case "gocyclo":
			var err error
			line, err = normalizeGocycloOutput(line)
			if err != nil {
				return nil, err
			}
		}

		filename, _, _, ok := parseDiagnostic(line)
		if !ok {
			return nil, fmt.Errorf("could not parse %s output %q", tool, line)
		}
		if !filepath.IsAbs(filename) && !pathWithin(dir, filename) {
			filename = filepath.Join(dir, filename)
		}

		for _, skip := range skipSuffixes {
			if strings.HasSuffix(filename, skip) {
				continue outer
			}
		}

		if autoGenerated(filename) {
			continue outer
		}

		filename = strings.TrimPrefix(filename, "_repos/src")
		dfn := displayFilename(filename)
		fs := fsMap[dfn]
		if fs.Filename == "" {
			fs.Filename = dfn
			fs.FileURL = fileURL(filename)
		}
		if err := fs.AddError(line); err != nil {
			return nil, err
		}
		fsMap[dfn] = fs
	}

	return fsMap, out.Err()
}

func pathWithin(dir, filename string) bool {
	rel, err := filepath.Rel(filepath.Clean(dir), filepath.Clean(filename))
	return err == nil && rel != ".." && !strings.HasPrefix(rel, ".."+string(filepath.Separator))
}

func normalizeGocycloOutput(line string) (string, error) {
	fields := strings.Fields(line)
	if len(fields) < 4 {
		return "", fmt.Errorf("could not parse gocyclo output %q", line)
	}

	complexity, err := strconv.Atoi(fields[0])
	if err != nil {
		return "", fmt.Errorf("could not parse gocyclo output %q: %w", line, err)
	}

	function := strings.Join(fields[2:len(fields)-1], " ")
	return fmt.Sprintf("%s: cyclomatic complexity %d in function %s (gocyclo)", fields[len(fields)-1], complexity, function), nil
}

func packageDirectories(dir string, filenames []string) ([]string, error) {
	packages := make(map[string]struct{})
	for _, filename := range filenames {
		rel, err := filepath.Rel(filepath.Clean(dir), filepath.Clean(filepath.Dir(filename)))
		if err != nil {
			return nil, fmt.Errorf("could not resolve package directory for %q: %w", filename, err)
		}
		if rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
			return nil, fmt.Errorf("file %q is outside checked directory %q", filename, dir)
		}
		if rel == "." {
			packages["."] = struct{}{}
		} else {
			packages["./"+filepath.ToSlash(rel)] = struct{}{}
		}
	}

	result := make([]string, 0, len(packages))
	for pkg := range packages {
		result = append(result, pkg)
	}
	sort.Strings(result)
	return result, nil
}

func isPackageTool(tool string) bool {
	switch tool {
	case "vet", "ineffassign", "golint", "staticcheck", "errcheck":
		return true
	default:
		return false
	}
}

type packageGroup struct {
	dir       string
	filenames []string
}

func packageGroups(dir string, filenames []string) ([]packageGroup, error) {
	root, err := filepath.Abs(dir)
	if err != nil {
		return nil, err
	}
	groupsByDir := make(map[string]*packageGroup)
	buildContext := build.Default
	if goos := os.Getenv("GOOS"); goos != "" {
		buildContext.GOOS = goos
	}
	if goarch := os.Getenv("GOARCH"); goarch != "" {
		buildContext.GOARCH = goarch
	}
	if cgoEnabled, ok := os.LookupEnv("CGO_ENABLED"); ok {
		buildContext.CgoEnabled = cgoEnabled != "0"
	}
	for _, filename := range filenames {
		absFilename, err := filepath.Abs(filename)
		if err != nil {
			return nil, err
		}
		if !pathWithin(root, absFilename) && !filepath.IsAbs(filename) {
			absFilename, err = filepath.Abs(filepath.Join(dir, filename))
			if err != nil {
				return nil, err
			}
		}
		if !pathWithin(root, absFilename) {
			return nil, fmt.Errorf("file %q is outside checked directory %q", filename, dir)
		}

		matched, err := buildContext.MatchFile(filepath.Dir(absFilename), filepath.Base(absFilename))
		if err != nil {
			return nil, fmt.Errorf("could not match Go file %q to build constraints: %w", filename, err)
		}
		if !matched {
			continue
		}

		moduleRoot := root
		current := filepath.Dir(absFilename)
		for {
			_, err := os.Stat(filepath.Join(current, "go.mod"))
			if err == nil {
				moduleRoot = current
				break
			}
			if !errors.Is(err, os.ErrNotExist) {
				return nil, fmt.Errorf("could not inspect module root %q: %w", current, err)
			}
			if current == root {
				break
			}
			parent := filepath.Dir(current)
			if parent == current || !pathWithin(root, parent) {
				break
			}
			current = parent
		}

		relativeRoot, err := filepath.Rel(root, moduleRoot)
		if err != nil {
			return nil, err
		}
		groupDir := dir
		if relativeRoot != "." {
			groupDir = filepath.Join(dir, relativeRoot)
		}
		key := filepath.Clean(groupDir)
		group := groupsByDir[key]
		if group == nil {
			group = &packageGroup{dir: groupDir}
			groupsByDir[key] = group
		}
		group.filenames = append(group.filenames, filename)
	}

	dirs := make([]string, 0, len(groupsByDir))
	for dir := range groupsByDir {
		dirs = append(dirs, dir)
	}
	sort.Strings(dirs)
	groups := make([]packageGroup, 0, len(dirs))
	for _, dir := range dirs {
		groups = append(groups, *groupsByDir[dir])
	}
	return groups, nil
}

func runPackageGroups(filenames, command []string, groups []packageGroup) (float64, []FileSummary, error) {
	failedByFile := make(map[string]FileSummary)
	var groupErrors []error
	for _, group := range groups {
		_, failed, err := GoTool(group.dir, group.filenames, command)
		if err != nil {
			groupErrors = append(groupErrors, fmt.Errorf("%s: %w", group.dir, err))
		}
		for _, summary := range failed {
			if existing, ok := failedByFile[summary.Filename]; ok {
				existing.Errors = append(existing.Errors, summary.Errors...)
				failedByFile[summary.Filename] = existing
			} else {
				failedByFile[summary.Filename] = summary
			}
		}
	}

	failed := make([]FileSummary, 0, len(failedByFile))
	for _, summary := range failedByFile {
		failed = append(failed, summary)
	}
	sort.Slice(failed, func(i, j int) bool {
		return failed[i].Filename < failed[j].Filename
	})
	if err := errors.Join(groupErrors...); err != nil {
		return 0, failed, err
	}
	return float64(len(filenames)-len(failed)) / float64(len(filenames)), failed, nil
}

func setModuleMode(cmd *exec.Cmd, dir string) {
	for _, name := range []string{"go.mod", "go.work"} {
		if _, err := os.Stat(filepath.Join(dir, name)); err == nil {
			return
		}
	}

	env := os.Environ()
	for i, value := range env {
		if strings.HasPrefix(value, "GO111MODULE=") {
			env[i] = "GO111MODULE=off"
			cmd.Env = env
			return
		}
	}
	cmd.Env = append(env, "GO111MODULE=off")
}

// GoTool runs a standalone Go analysis command on a directory.
func GoTool(dir string, filenames, command []string) (float64, []FileSummary, error) {
	if len(command) == 0 {
		return 0, []FileSummary{}, fmt.Errorf("no command provided")
	}
	if len(filenames) == 0 {
		return 1, []FileSummary{}, nil
	}

	tool := filepath.Base(command[0])
	goVet := tool == "go" && len(command) > 1 && command[1] == "vet"
	if goVet {
		tool = "vet"
	}

	packageToolFilenames := filenames
	if isPackageTool(tool) {
		groups, err := packageGroups(dir, filenames)
		if err != nil {
			return 0, []FileSummary{}, err
		}
		if len(groups) == 0 {
			return 1, []FileSummary{}, nil
		}
		var activeFilenames []string
		for _, group := range groups {
			activeFilenames = append(activeFilenames, group.filenames...)
		}
		if len(groups) > 1 || filepath.Clean(groups[0].dir) != filepath.Clean(dir) {
			return runPackageGroups(activeFilenames, command, groups)
		}
		packageToolFilenames = groups[0].filenames
	}

	if tool == "misspell" && len(filenames) > 300 {
		log.Println("disabling misspell on large repo...")
		return 1, []FileSummary{}, nil
	}
	if tool == "ineffassign" && len(filenames) > 100 {
		log.Println("disabling ineffassign on large repo...")
		return 1, []FileSummary{}, nil
	}

	params := append([]string{}, command[1:]...)
	switch tool {
	case "gofmt", "gocyclo", "misspell":
		params = append(params, filenames...)
	case "vet", "ineffassign", "golint", "staticcheck", "errcheck":
		packageArgs := params
		if goVet && len(packageArgs) > 0 {
			packageArgs = packageArgs[1:]
		}
		if !hasPackageArgument(packageArgs) {
			packages, err := packageDirectories(dir, packageToolFilenames)
			if err != nil {
				return 0, []FileSummary{}, err
			}
			params = append(params, packages...)
		}
	default:
		return 0, []FileSummary{}, fmt.Errorf("unsupported Go tool %q", tool)
	}

	cmd := exec.Command(command[0], params...)
	if isPackageTool(tool) {
		cmd.Dir = dir
		setModuleMode(cmd, dir)
	}

	output, runErr := cmd.CombinedOutput()
	out := bufio.NewScanner(strings.NewReader(string(output)))
	fsMap, err := getFileSummaryMap(out, dir, tool)
	if err != nil {
		return 0, []FileSummary{}, err
	}

	failed := make([]FileSummary, 0, len(fsMap))
	for _, summary := range fsMap {
		failed = append(failed, summary)
	}
	sort.Slice(failed, func(i, j int) bool {
		return failed[i].Filename < failed[j].Filename
	})

	if runErr != nil {
		exitErr, ok := runErr.(*exec.ExitError)
		allowedExit := ok && len(failed) > 0 && exitErr.ExitCode() == 1
		if tool == "misspell" && ok && len(failed) > 0 && exitErr.ExitCode() == 2 {
			allowedExit = true
		}
		if !allowedExit {
			return 0, failed, fmt.Errorf("%s failed: %w: %s", command[0], runErr, strings.TrimSpace(string(output)))
		}
	}

	if len(filenames) == 1 {
		lc, err := lineCount(filenames[0])
		if err != nil {
			return 0, failed, err
		}

		var errors int
		if len(failed) != 0 {
			errors = len(failed[0].Errors)
		}
		return float64(lc-errors) / float64(lc), failed, nil
	}

	return float64(len(filenames)-len(failed)) / float64(len(filenames)), failed, nil
}

func hasPackageArgument(args []string) bool {
	for _, arg := range args {
		if !strings.HasPrefix(arg, "-") {
			return true
		}
	}
	return false
}
